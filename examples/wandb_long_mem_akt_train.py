import argparse
from wandb_train import main

if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--dataset_name", default="assist2009")
    p.add_argument("--model_name", default="long_mem_akt")
    p.add_argument("--emb_type", default="qid")
    p.add_argument("--save_dir", default="saved_model")
    p.add_argument("--seed", type=int, default=3407)
    p.add_argument("--fold", type=int, default=0)
    p.add_argument("--d_model", type=int, default=128)
    p.add_argument("--n_blocks", type=int, default=2)
    p.add_argument("--num_attn_heads", type=int, default=8)
    p.add_argument("--d_ff", type=int, default=256)
    p.add_argument("--final_fc_dim", type=int, default=512)
    p.add_argument("--kq_same", type=int, default=1)
    p.add_argument("--separate_qa", type=int, default=0)
    p.add_argument("--l2", type=float, default=1e-5)
    p.add_argument("--vector_gate", type=int, default=0)
    p.add_argument("--write_encoding", choices=["causal", "independent"], default="causal")
    p.add_argument("--score_protocol", choices=["legacy", "student"], default="legacy")
    p.add_argument("--dropout", type=float, default=.1)
    p.add_argument("--num_slots", type=int, default=32)
    p.add_argument("--block_size", type=int, default=200)
    p.add_argument("--tbptt_blocks", type=int, default=2)
    p.add_argument("--time_weight", type=int, default=1)
    p.add_argument("--event_distance_fallback", type=int, default=0)
